/**
 * berean.db schema golden (M3-01): every SQL statement the TypeScript migrations execute on a NEW
 * database, recorded per version, plus the resulting schema (sqlite_master) and seed rows. The native
 * store replays the statements (ADR-0009) and must reproduce the schema byte for byte. Migrations
 * 1–17 contain data-dependent JavaScript; the recording is only the fresh-database path, which is
 * exactly what replay is used for (plus pure-SQL upgrades from v18+).
 */
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { openNodeSqlite } from '../../electron/db/adapters/nodeSqliteAdapter'
import type { DatabaseAdapter } from '../../src/platform/db/DatabaseAdapter'
import { BEREAN_MIGRATIONS, BEREAN_SCHEMA_VERSION, runMigrations } from '../../src/platform/db/bereanMigrations'

const ROOT = resolve(__dirname, '../..')
type Stmt = { exec: string } | { run: string; params: unknown[] }
/** Date.now() is frozen to this sentinel while recording (v45 stamps copied rows with "now"); the native
 *  runner substitutes the real current time for it at replay (Migrator.nowPlaceholder). */
export const NOW_SENTINEL = 1111111111111

function recording(target: DatabaseAdapter, log: Stmt[]): DatabaseAdapter {
  return new Proxy(target, {
    get(t, prop, recv) {
      const v = Reflect.get(t, prop, recv)
      if (prop === 'exec') return async (sql: string) => { log.push({ exec: sql }); return (v as DatabaseAdapter['exec']).call(t, sql) }
      if (prop === 'run') return async (sql: string, params?: unknown[]) => { log.push({ run: sql, params: params ?? [] }); return (v as DatabaseAdapter['run']).call(t, sql, params as never) }
      if (prop === 'transaction') return async <T>(fn: (tx: DatabaseAdapter) => Promise<T>) => (v as DatabaseAdapter['transaction']).call(t, (tx: DatabaseAdapter) => fn(recording(tx, log)))
      return typeof v === 'function' ? v.bind(t) : v
    },
  })
}

export async function dumpSchema(db: DatabaseAdapter) {
  const objects = await db.all<{ type: string; name: string; tbl_name: string; sql: string | null }>(
    "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' ORDER BY type, name")
  const settings = await db.all<{ key: string; value: string }>('SELECT key, value FROM settings ORDER BY key')
  const versions = (await db.all<{ version: number }>('SELECT version FROM schema_version ORDER BY rowid')).map((r) => r.version)
  return { objects, settings, versions }
}

export async function buildSchemaGolden(): Promise<{ name: string; data: unknown }> {
  // Per-version statements: migrate one version at a time, recording only that step.
  const db = openNodeSqlite(':memory:', 'schema-golden')
  await db.exec('PRAGMA foreign_keys = ON')
  const origLog = console.log
  console.log = () => {}
  const origNow = Date.now
  Date.now = () => NOW_SENTINEL
  const steps: Array<{ version: number; statements: Stmt[] }> = []
  const checkpoints: Record<string, unknown> = {}
  try {
    for (const m of BEREAN_MIGRATIONS) {
      const log: Stmt[] = []
      await runMigrations(recording(db, log), BEREAN_MIGRATIONS.filter((x) => x.version <= m.version))
      // Drop the runner's own bookkeeping; the native runner issues its own.
      steps.push({ version: m.version, statements: log.filter((s) => !('run' in s && s.run.startsWith('INSERT INTO schema_version'))
        && !('exec' in s && s.exec.startsWith('CREATE TABLE IF NOT EXISTS schema_version'))) })
      if ([17, 18, 43, 47, 48].includes(m.version)) checkpoints[`v${m.version}`] = await dumpSchema(db)
    }
    checkpoints.final = await dumpSchema(db)
  } finally {
    console.log = origLog
    Date.now = origNow
  }
  await db.close()
  return {
    name: 'schema',
    data: {
      format: 1, generator: 'scripts/golden/schema.ts',
      sources: Object.fromEntries(['src/platform/db/bereanMigrations.ts', 'scripts/golden/schema.ts'].map((p) => [p, createHash('sha256').update(readFileSync(resolve(ROOT, p))).digest('hex')])),
      schemaVersion: BEREAN_SCHEMA_VERSION,
      steps, checkpoints,
    },
  }
}

export const SWIFT_MIGRATIONS_PATH = resolve(ROOT, 'Packages/BereanKit/Sources/BereanStore/Generated/RecordedMigrations.swift')

/** The recorded steps as Swift source (statements as raw string literals; params as JSON literals). */
export async function buildRecordedMigrationsSwift(): Promise<string> {
  const g = (await buildSchemaGolden()).data as { schemaVersion: number; steps: Array<{ version: number; statements: Stmt[] }> }
  const lit = (x: string) => { if (x.includes('"""#')) throw new Error('raw literal terminator in SQL'); return `#"""\n${x}\n"""#` }
  const param = (v: unknown) => v === null ? '.null' : v === NOW_SENTINEL ? '.integer(Migrator.nowPlaceholder)' : typeof v === 'number' ? (Number.isInteger(v) ? `.integer(${v})` : `.real(${v})`) : `.text(${lit(String(v))})`
  const out = ['// GENERATED by scripts/golden/schema.ts from src/platform/db/bereanMigrations.ts (fresh-database path).',
    '// Do not edit — run `npm run golden:export`. See DECISIONS ADR-0009.', '', 'import BereanSQLite', '',
    'extension Migrator {', `    /// BEREAN_SCHEMA_VERSION of the TypeScript this was recorded from.`, `    public static let recordedSchemaVersion = ${g.schemaVersion}`,
    '    public static let recordedSteps: [Step] = [']
  for (const st of g.steps) {
    out.push(`        Step(version: ${st.version}, statements: [`)
    for (const s of st.statements) {
      if ('exec' in s) out.push(`            .exec(${lit(s.exec)}),`)
      else out.push(`            .run(${lit(s.run)}, [${s.params.map(param).join(', ')}]),`)
    }
    out.push('        ]),')
  }
  out.push('    ]', '}')
  return out.join('\n') + '\n'
}
