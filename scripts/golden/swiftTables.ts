/**
 * Generates Packages/BereanKit/Sources/BereanReference/Generated/ReferenceTables.swift from the
 * TypeScript tables (src/lib/parseRef.ts, hermasMap.ts) so the native book catalogue can never
 * drift from the oracle. Written by `npm run golden:export`; checked by tests/unit/goldenCorpus.test.ts.
 */
import { resolve } from 'node:path'
import { ALL_BOOKS, AMBIGUOUS_PATTERNS, getTranslationForBook, maxChapterFor, resolveBookToken } from '../../src/lib/parseRef'
import { getHermasSections, type HermasBookId } from '../../src/lib/hermasMap'
import { defaultWordReplacerRules } from './display'

const q = (s: string) => JSON.stringify(s)   // ASCII-only tables: a JSON string literal is a valid Swift literal

export const SWIFT_TABLES_PATH = resolve(__dirname, '../../Packages/BereanKit/Sources/BereanReference/Generated/ReferenceTables.swift')

export function buildReferenceTablesSwift(): string {
  for (const b of ALL_BOOKS) for (const s of [b.id, b.name, ...b.patterns]) if (!/^[\x20-\x7e]*$/.test(s)) throw new Error(`non-ASCII table entry: ${s}`)
  const lines: string[] = []
  lines.push('// GENERATED by scripts/golden/swiftTables.ts from src/lib/parseRef.ts + src/lib/hermasMap.ts.')
  lines.push('// Do not edit — run `npm run golden:export`.')
  lines.push('')
  lines.push('enum ReferenceTables {')
  lines.push('    /// BOOK_MAP in canonical order: (id, name, patterns).')
  lines.push('    static let books: [(id: String, name: String, patterns: [String])] = [')
  for (const b of ALL_BOOKS) lines.push(`        (${q(b.id)}, ${q(b.name)}, [${b.patterns.map(q).join(', ')}]),`)
  lines.push('    ]')
  // PATTERN_LOOKUP is last-write-wins across BOOK_MAP; resolveBookToken's tier 1 returns it verbatim.
  const lookup = new Map<string, string>()
  for (const b of ALL_BOOKS) for (const p of b.patterns) lookup.set(p, resolveBookToken(p) ?? '')
  lines.push('    /// PATTERN_LOOKUP (duplicate patterns resolve to the LAST book that lists them).')
  lines.push('    static let patternLookup: [String: String] = [')
  for (const [p, id] of [...lookup.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) lines.push(`        ${q(p)}: ${q(id)},`)
  lines.push('    ]')
  lines.push('    static let maxChapters: [String: Int] = [')
  for (const b of ALL_BOOKS) { const m = maxChapterFor(b.id); if (m !== undefined) lines.push(`        ${q(b.id)}: ${m},`) }
  lines.push('    ]')
  lines.push('    /// BOOK_TRANSLATION ("hermas" is replaced by the selected Hermas translation at runtime).')
  lines.push('    static let bookTranslation: [String: String] = [')
  for (const b of ALL_BOOKS) { const t = getTranslationForBook(b.id); if (t) lines.push(`        ${q(b.id)}: ${q(t)},`) }
  lines.push('    ]')
  lines.push('    static let ambiguousPatterns: Set<String> = [')
  for (const p of [...AMBIGUOUS_PATTERNS].sort()) lines.push(`        ${q(p)},`)
  lines.push('    ]')
  lines.push('    /// Shepherd of Hermas sections per variant: book -> [(sectionName, sectionNum, chapters)].')
  for (const variant of ['rd', 'taylor'] as const) {
    lines.push(`    static let hermasSections_${variant}: [String: [(name: String, num: Int, chapters: [Int])]] = [`)
    for (const id of ['HER_VIS', 'HER_MAN', 'HER_SIM'] as HermasBookId[]) {
      lines.push(`        ${q(id)}: [`)
      for (const s of getHermasSections(id, variant)) lines.push(`            (${q(s.sectionName)}, ${s.sectionNum}, [${s.chapters.join(', ')}]),`)
      lines.push('        ],')
    }
    lines.push('    ]')
  }
  lines.push('}')
  return lines.join('\n') + '\n'
}

export const SWIFT_RULES_PATH = resolve(__dirname, '../../Packages/BereanKit/Sources/BereanText/Generated/DefaultWordReplacerRules.swift')

/** DEFAULT_WORD_REPLACER_RULES (src/store/index.ts) as Swift. */
export function buildDefaultRulesSwift(): string {
  const lines = ['// GENERATED by scripts/golden/swiftTables.ts from src/store/index.ts (DEFAULT_WORD_REPLACER_RULES).',
    '// Do not edit — run `npm run golden:export`.', '', 'extension WordReplacer {',
    '    /// The rules a new install starts with (Strong\'s restorations first, then text rules).',
    '    public static let defaultRules: [WordReplacerRule] = [']
  for (const r of defaultWordReplacerRules()) {
    lines.push(`        WordReplacerRule(id: ${JSON.stringify(r.id)}, queries: [${r.queries.map((x) => JSON.stringify(x)).join(', ')}], replacement: ${JSON.stringify(r.replacement)}, wholeWord: ${r.wholeWord}, enabled: ${r.enabled}${r.strongsNum ? `, strongsNum: ${JSON.stringify(r.strongsNum)}` : ''}),`)
  }
  lines.push('    ]', '}')
  return lines.join('\n') + '\n'
}
